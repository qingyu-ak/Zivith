let relSeq = 0;
function relationship(
  kind: string,
  a: string,
  b: string,
  label: string,
  description: string,
  direction: 'one_way' | null = null,
): WorldRelationshipDTO {
  relSeq += 1;
  return {
    id: `rel_mock_${relSeq}`,
    project_id: PROJECT_ID,
    kind,
    source_type: 'asset',
    source_id: a,
    target_type: 'asset',
    target_id: b,
    direction,
    label,
    description,
    state: 'approved',
    created_at: T0,
  };
}

/** 角色出现在某个场景（Entity 绑定空间：登场记录） */
